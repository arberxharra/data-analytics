# Example assets
cash = 2500
savings = 4000
car_value = 8000

# Example debts
credit_card_debt = 700
car_loan = 3000

# Calculate totals
total_assets = cash + savings + car_value
total_debts = credit_card_debt + car_loan
net_worth = total_assets - total_debts

# Display the results
print("Your total assets are " + str(total_assets))
print("Your total debts are " + str(total_debts))
print("Your net worth is " + str(net_worth))